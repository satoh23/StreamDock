#!/usr/bin/env python3
"""063c 段 2-b: ガチャ演出の素材を 1 枚のシートから切り出す（**一度きりの道具**）。

⚠⚠⚠ **これはビルドの一部ではない。** 生成物（PNG）はリポジトリにコミットしてあるので、
アプリのビルドにも CI にも Python は要らない（＝ **新規依存ゼロ**を守るための構え）。
このスクリプトが在るのは、⚠ **元シートの透過が自動マットで、手では二度と再現できない**からである
（座標表ごと残しておかないと、次に素材を足したい人が作り直せない）。

## 使い方

    python3 docs/assets-source/extract-gacha-assets.py

`docs/assets-source/gacha-sheet.png` を読み、`apps/desktop/src/assets/gacha/` を**作り直す**。

## ⚠ 切り出しの方針（変えるときはここを読むこと）

- ⚠⚠ **拡大しない**（シート上の解像度のまま出す）。表示倍率は CSS が持つ。
  先に LANCZOS で拡大して焼き込む案は**採らなかった**——ブラウザの拡大と品質差がほとんど無い一方、
  **バンドルサイズだけが増える**（マシン 1 コマで約 4 倍）。
- ⚠⚠⚠ **連番は「同じ高さの箱」で切り、絵を箱の中央に置く**（コマごとに切り詰めない）。
  切り詰めると**コマ送りで絵が跳ねる**（各コマの重心がずれるため）。
  ⚠ **高さ**なのは、CSS が `height` を指定して `width: auto` にしているから
  （＝**見た目の大きさを決めるのは箱の高さ**で、幅は絵が中央に在りさえすれば違ってよい）。
  ⚠⚠ 063c 段 2-c で**カプセル 4 コマ目だけ幅が違う**のはこの規則による（下の [`OPEN_BOX`] を見ること）。
- ⚠ **セクション見出しの白帯と「ファイル形式・仕様」ボックスはシートの透過に乗っている**ので、
  箱の座標で必ず外すこと。
- ⚠⚠⚠ **文字が焼き込まれている素材は「言っていることが測れるもの」だけ使う。**
  シートには「大当たり！」のカードとテロップが在るが、⚠ **どの景品が当たっても「大当たり」と出る**のは
  視聴者に対する嘘になる（当たりやすさは景品ごとに違う）。⇒ **使わない。**
  ⚠⚠ **「レア！」は 063c 段 3 で解禁した**——当たりやすさは `prize.weight`（＝ユーザーが打った％そのもの）
  なので **10% 未満かどうかは測れる**（判定は `isGachaRarePrize` 1 か所）。
  ⇒ 使うのは「ガチャ！」「パカッ！」「レア！」の 3 つで、**景品名は必ずアプリ側が文字として描く**。
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(__file__).resolve().parent / "gacha-sheet.png"
OUT = ROOT / "apps" / "desktop" / "src" / "assets" / "gacha"

# ⚠ シートの実寸（変わったら座標表が全部ずれるので、読み込み時に検査する）。
SHEET_SIZE = (1536, 1024)

# --- 座標表（left, top, right, bottom）-----------------------------------------------
#
# ⚠⚠ **連番は同じ幅・高さで並べてある**（上記「同じ大きさの箱で切る」）。

# ⚠⚠⚠ **切り出す前に消す帯**（セクションの見出し）。
#
# シートの見出しは**不透明**でシートの透過に乗っているため、素材の箱に食い込む:
#   - 見出し 1（y 8-46）… ガチャマシンの箱の**上端 10px** に入る
#   - 見出し 3（y 272-297）／見出し 5（y 455-484）… カプセル開封の箱の**上下**に入る
# ⚠ 箱を狭めて逃げると**コマごとに大きさが変わる**（＝コマ送りで跳ねる）ので、
# **帯のほうを消してから切る**。⚠⚠ 座標は実測の bbox に数 px 余裕を持たせたもので、
# **素材そのものには 1px も掛かっていない**（金のバーストは y 490 から始まる）。
MASK_RECTS = [
    (0, 0, 300, 48),  # 見出し 1
    (0, 262, 300, 300),  # 見出し 3
    (0, 446, 310, 486),  # 見出し 5
]

# 1. ガチャマシン: **5 コマだけ使う**。1〜4＝ハンドルが回る／5＝カプセルが出てくる。
#    ⚠ 箱は 132×240 固定。中心の間隔は約 149px（シート上で等間隔に並んでいる）。
#
#    ⚠⚠⚠ **063c 段 2-c: 6 コマ目（一番右）は使わない。**
#    理由＝**排出されるカプセルの色が違う**（6 コマ目は青／桃、5 コマ目は赤／白）。
#    ⚠ カプセル開封アニメーション（下の [`OPEN_BOX`]）は**赤／白**なので、
#    6 コマ目を挟むと **「青いカプセルが出てきて、赤いカプセルが割れる」**——
#    絵として別のものにすり替わる。⇒ **排出は 5 コマ目 1 枚を持たせる**
#    （何ミリ秒持たせるかは `gachaStagePlayback.ts` の `GACHA_DISPENSE_MS` が持つ）。
MACHINE_BOX_W, MACHINE_BOX_H = 132, 240
MACHINE_TOP = 36
MACHINE_CENTERS_X = [82, 232, 382, 530, 680]

# 3. カプセル開封: 4 コマ使う（閉じている → ひび → 開いて発光 → **二つに割れる**）。
#    ⚠⚠ **6 コマ目（一番右）は使わない**——白いカードに「大当たり！」が焼き込まれているため（上記）。
#    ⚠ 箱の**高さは 184 固定**（幅は 4 コマ目だけ違う・冒頭の「同じ高さの箱で切る」が正）。
#
#    ⚠⚠⚠ **063c 段 2-c: 4 コマ目はシートの 5 番目のセルである**（4 番目ではない）。
#    実機で見て分かったこと＝ **4 番目のセルは「上に半球・下に二つの欠片」＝ 3 つに割れて見える**うえ、
#    ⚠ 箱（140 幅）に**収まっておらず左右が見切れていた**。カプセルは**二つに割れる**のが正しい。
#    ⇒ **二つの欠片がはっきり分かれている 5 番目のセル**（白い欠片・赤い欠片・光・金の粒）へ差し替えた。
#    ⚠⚠ **このセルの白いカードは無地である**（文字は 6 番目のセルにしか無い）ので、
#    冒頭の「文字が焼き込まれている素材は使わない」に**抵触しない**。
#    ⚠ 幅 192 なのは**このセルの絵が 164px 幅あり、140 では切れるから**で、
#    箱の中心（654）を**絵の中心に合わせてある**（＝ CSS の `height` 指定では他コマと同じ大きさに見える）。
#
#    ⚠⚠⚠ **2〜4 コマ目は隣と地続きである**（実測: y300-455 の帯で x130〜550 に空白列が 1 本も無い＝
#    発光どうしが重なっている）。⇒ **境目は「重なりの真ん中」で切るしかない**。
#    ⚠ そのまま切ると**まっすぐな切り口が線として見える**ので、左右の端を [`EDGE_FADE_PX`] px かけて
#    透明へ落とす。⚠ 1 コマ目は端まで余白なので、同じ処理をしても**絵は 1px も変わらない**
#    （4 コマに同じ扱いをすることのほうが大事＝コマ間で明るさが変わらない）。
EDGE_FADE_PX = 14
OPEN_BOX = [
    (0, 280, 140, 464),
    (128, 280, 268, 464),
    (265, 280, 405, 464),
    (558, 280, 750, 464),  # ⚠ シートの 5 番目のセル（上記）。左右に空白があるので隣と干渉しない
]

# 5. 背景エフェクト・パーティクル（⚠⚠ **使うのは金の粒 1 つだけ**）。
#
# ⚠⚠⚠ **063c 段 2-c: 金のバーストと黄色い光球はやめた。**
# 実機で見て分かったこと＝ **放射状のバーストが画面の半分を占めて、景品名より強い**。
# ⇒ 1 段下の**金の粒（キラキラ）だけ**にした。⚠ 粒は「背景を明るくする」だけで**主役を食わない**。
#
# ⚠⚠ **光は「どこで終わるか」が絵の中に無い**（放射状に薄れて隣の素材と地続きになる）。
# ⇒ **四辺を透明へ落とす**。⚠ 狭く取ると **配信画面に四角い切り口がそのまま出る**
# （実測: 780px へ拡大したとき、上辺の直線がはっきり見えた）。
#
# ⚠ 上辺だけ事情が違う: **真上にあるバーストの裾がここまで垂れてきている**（実測: y578 で α=111、
#   y580 で 107、粒そのものは y590 から）。⇒ **落とし幅は 12px**——18px にすると
#   一番大きい粒の上のトゲまで薄くなる。
SPARKLE_GOLD = (12, 578, 156, 664)
SPARKLE_FADE_PX = 12

# 6. 演出用テロップ（⚠ **中立な 3 つだけ**・上記の理由）。
#
# ⚠⚠⚠ **063c 段 3 で「レア！」を解禁した。** 段 2-b では「レア度という概念を 063 は持っていない」として
# 使わなかったが、⚠ **持っていないのは概念ではなく経路のほうだった**——
# 当たりやすさは **`prize.weight`（＝ユーザーが打った％そのもの・分母は 1000 固定）**なので、
# 「10% 未満なら出す」は**測れるし、嘘にならない**（`isGachaRarePrize` が唯一の判定）。
# ⚠⚠ **「大当たり！」は解禁していない**——あちらは**どの景品でも同じ文字が出る**ので嘘になる。
# ⚠ 「？！」も使わない（何を指すのか演出の側で決まらない）。
TELOP_GACHA = (652, 504, 804, 592)
TELOP_PAKA = (648, 592, 792, 676)
TELOP_RARE = (716, 674, 850, 736)


def crop(
    im: Image.Image,
    box: tuple[int, int, int, int],
    name: str,
    fade: int = 0,
    fade_vertical: bool = False,
) -> None:
    """箱で切り出す。⚠ `fade` を渡すと端を透明へ落とす（切り口を線として見せない）。

    ⚠ `fade_vertical` は上下も落とすか。**連番（カプセル）は左右だけ**である——
    上下も落とすと**カプセルの上端と下端が薄くなる**（あちらは切り口ではなく絵の縁）。
    """
    piece = im.crop(box)
    if fade > 0:
        alpha = piece.getchannel("A")
        px = alpha.load()
        for i in range(fade):
            k = (i + 1) / (fade + 1)
            for y in range(piece.height):
                px[i, y] = int(px[i, y] * k)
                px[piece.width - 1 - i, y] = int(px[piece.width - 1 - i, y] * k)
            if fade_vertical:
                for x in range(piece.width):
                    px[x, i] = int(px[x, i] * k)
                    px[x, piece.height - 1 - i] = int(px[x, piece.height - 1 - i] * k)
        piece.putalpha(alpha)
    piece.save(OUT / f"{name}.png")
    print(f"  {name}.png  {box[2] - box[0]}x{box[3] - box[1]}")


def main() -> None:
    im = Image.open(SRC).convert("RGBA")
    if im.size != SHEET_SIZE:
        raise SystemExit(
            f"シートの実寸が変わっている（{im.size} != {SHEET_SIZE}）。座標表を見直すこと。"
        )
    # ⚠ 見出しの帯を消してから切る（上の MASK_RECTS の注記が正）。
    clear = Image.new("RGBA", im.size, (0, 0, 0, 0))
    for rect in MASK_RECTS:
        im.paste(clear.crop(rect), rect)

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.png"):
        old.unlink()

    for i, cx in enumerate(MACHINE_CENTERS_X, start=1):
        box = (
            cx - MACHINE_BOX_W // 2,
            MACHINE_TOP,
            cx + MACHINE_BOX_W // 2,
            MACHINE_TOP + MACHINE_BOX_H,
        )
        crop(im, box, f"machine-{i}")

    for i, box in enumerate(OPEN_BOX, start=1):
        crop(im, box, f"capsule-{i}", fade=EDGE_FADE_PX)

    crop(im, SPARKLE_GOLD, "sparkle", fade=SPARKLE_FADE_PX, fade_vertical=True)
    crop(im, TELOP_GACHA, "telop-gacha")
    crop(im, TELOP_PAKA, "telop-paka")
    crop(im, TELOP_RARE, "telop-rare")

    total = sum(p.stat().st_size for p in OUT.glob("*.png"))
    print(f"合計 {len(list(OUT.glob('*.png')))} 枚 / {total / 1024:.0f} KB")


if __name__ == "__main__":
    main()
