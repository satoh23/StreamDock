//! 062b: 配信セッション（「1 回の配信」）の記録。
//!
//! 038a の `viewer_comments.session_id` は**コメビュ窓のマウント単位**で採番されていたため、
//! 「窓を開き直すと 1 回の配信が複数に分裂する」「窓を開きっぱなしで 2 日配信すると 2 回が 1 つに混ざる」
//! という状態だった。本モジュールは**開始/終了時刻・プラットフォーム・手入力タイトル**を持つ
//! `stream_sessions` を用意し、062c（サマリー）/062d（フィルタ）が集計する単位を確定させる。
//!
//! セキュリティ（docs/security.md §9 追補〔062b〕）:
//! - 保存するのは**時刻・プラットフォーム・ユーザー自身が入力したタイトル**だけで、
//!   **第三者の個人データはこの表に 1 つも入らない**（視聴者名・本文・金額は `viewer_memory` の担当）。
//! - セッション境界は**既に受信済みの接続状態と受信済みコメント**からのみ判定する。
//!   **新規の外部通信・宛先・購読・スコープ・capability はゼロ**。
//! - 識別子（テーブル名・カラム名・ORDER BY 句）は**コンパイル時定数のみ**、値はパラメータバインド（§8）。
//! - コマンドはすべて単一目的（§3）。とくに閉じ忘れ回収は**猶予時間を引数に取らない**
//!   （取ると frontend が `0` を渡すだけで進行中セッションを全部終了できてしまう）。
//!
//! tools / viewer_memory と同型のレイヤード構成（commands / service / repository / model）。
