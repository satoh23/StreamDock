//! 063h: ガチャの抽選結果の記録（`gacha_draws`）／063i: その読み出し。
//!
//! tools / viewer_memory / stream_session と同型のレイヤード構成（commands / service / repository / model）。
//!
//! ## ⚠⚠⚠ 「すべての抽選を残す」（本モジュールの存在理由）
//!
//! 依頼者の判断（2026-08-30）＝「**そもそもハズレという概念がない**ため全て記録して欲しい。
//! **ハズレ無しのガチャを作る配信者もいるはず**なので」。
//! ⇒ **何も当たらなかった抽選も 1 回の抽選として等しく 1 行残す**（`prize_label` が `NULL` になる）。
//! ⚠ **画面にも DB にも「ハズレ」という語を持ち込まない**（画面表記は frontend の `GACHA_MISS_LABEL`）。
//!
//! ⚠⚠ **`prize_label` に「何も出ない」という文字列を入れないこと。** 入れると
//! **「そういう名前の景品」と区別できなくなる**——ユーザーは景品名を自由に付けられる。
//!
//! ## セキュリティ（docs/security.md 準拠・**正は §9 追補〔063h〕**）
//!
//! - **§1 外部通信ゼロ**: 保存するのは**すでに受信済みの値**だけで、増えるのは Tauri コマンド 1 本。
//!   新規の egress・宛先・購読・スコープ・capability・依存は**すべて 0**（`csp: null` 不変）。
//! - **§3 最小権限**: コマンドは [`commands::record_gacha_draw`]（記録）と
//!   [`commands::list_gacha_draws`]（**読み出し・063i**）の **2 本だけ**で、
//!   ⚠ **読み出しの引数はセッション id 1 つだけ**である（§9 追補〔063h〕§3 が名指しで求めている線）。
//!   ⚠⚠ **削除・更新・一括操作のコマンドを作らないこと**——アプリ定義コマンドは **ACL を通らず
//!   全窓から呼べる**ので、「任意の行を消せる／書き換えられる」能力を構造側に持たせない
//!   （062b の §3 の議論と同じ）。削除は既存の `delete_viewer` / `clear_viewers` に相乗りする。
//!   ⚠ 063i は**保存を 1 ミリも動かしていない**（読み取り専用コマンドを 1 本足しただけで、
//!   テーブルも列も 1 つも増えていない）。
//! - **§8**: 識別子（テーブル名・カラム名・ORDER BY 句）は**コンパイル時定数のみ**、値は必ず
//!   パラメータバインド。⚠ **SQL を `format!` で組み立てない**（列名の共有は `concat!` で行う＝
//!   コンパイル時連結なので実行時の連結が 1 か所も無い）。検証は frontend ではなく [`service`] が持つ。
//! - **§9**: 端末内保存の限定解禁の 4 つ目。**コメント本文・投げ銭金額・アバター・引き金のコメント id
//!   を列として持たない**。ログに景品名・ガチャ名・表示名・視聴者 id・件数を出さない。
//!
//! ## ⚠⚠ `viewer_id` に FK を張らない（**次の人が「張り忘れ」と誤読する**）
//!
//! 理由は 2 つあり、どちらも回避不能である（§9 追補〔063h〕が正）:
//!
//! 1. **記録の順序が保証できない。** コメントの記録（＝`viewers` 行を作る側）は fire-and-forget で、
//!    セッション id が未確定ならバッファに貯まる。抽選の記録が先に走ると **FK 違反で INSERT が落ち、
//!    しかもその失敗は握り潰される**＝「**画面で当たったのに履歴に無い**」が静かに起きる。
//! 2. **抽選側で `viewers` 行を先に作ると、038c の初見／久しぶり判定が壊れる。**
//!    あの判定は `viewers` 行が**その時点で存在しないこと**で決まる
//!    （`viewer_memory::repository` の `prior_last`）。⇒ 「FK を通すために親を先に作る」という
//!    回避策そのものが**別機能の回帰**になる。
//!
//! ⚠⚠⚠ **代わりに削除を明示 DELETE で行う**（[`repository::delete_by_viewer`] / [`repository::delete_all`]）。
//! 呼び出し元は `viewer_memory::service` の `delete` / `clear` で、**同一トランザクション**・
//! **ガチャ履歴を先に**消す。⚠ **一括削除・エクスポートを作る人は `gacha_draws` を明示的に対象へ含めること**
//! （CASCADE では消えない）。
//!
//! ## ⚠ `session_id` にも FK を張らない
//!
//! `stream_sessions` への FK は **062b が既に張っていない**（`viewer_comments.session_id` と同じ扱い）。
//! 本モジュールもそれに揃える＝**緩い関連**（アプリ側で突き合わせるだけ）。
//! ⚠ 062b 以前の `session_id` を持つ行は今後も作られないが、**古い配信のサマリーは空になる**
//! （記録は遡れない＝063h / 063i の明示的な決定）。

