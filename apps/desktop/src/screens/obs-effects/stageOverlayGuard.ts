import {
  loadGachaStageEnabled,
  loadStageOverlayEnabled,
} from "../../features/comment-viewer/overlaySettings";
import { referencedGachaIds } from "./effectAssignments";

/**
 * 063c 段 1: **ステージ窓（label `stage-overlay`）を開いて OBS へ繋いでよいか**を決める
 * ⚠⚠⚠ **`docs/security.md` §1（044a 例外）を守る唯一のガード**。
 *
 * ## ⚠⚠⚠ なぜ「関数 1 本」でなければならないのか
 *
 * 064e が「OBS へ自動で反映」トグルを削除して以降、**OBS へ繋ぐかどうかを決めているのは旗だけ**になり、
 * §1 の 064e 追補は「**旗 true ＝ ユーザーが『開始』ボタンを押した**」という**同値**に全体重を乗せている。
 * ⚠⚠ **063c 段 1 で旗が 2 本になった**（配信イベントの開催／ガチャ演出の明示トグル）ので、
 * **読み手が旗を直に読むと、条件の書き方が読み手の数だけ増える**——
 * ⚠ そうなると §1 が「ガードはここ」と指せる場所が無くなり、
 * **片方の読み手だけが新しい旗を知らない**（＝ある経路からは無操作で OBS へ繋ぐ）が作れてしまう。
 * ⇒ **判定をこの 1 本に閉じ、読み手は全員ここを通す。**
 *
 * ⚠⚠ **読み手は 3 つだけ**（`grep -rn "isStageOverlayRequired" src` で確認できる）:
 *   1. [`restoreEffectOverlayWindow`]（**起動時の窓復元**・`App.tsx` から注入）
 *   2. `CommentViewerApp` の **`storage` 購読**（旗・条件が変わった瞬間の反映）
 *   3. `CommentViewerApp` の **WS 接続確立時 reconcile**（061e(5) の保証ベースライン）
 * ⚠ `obs-enable` を送れる WS を持つのはコメビュ窓だけなので、2 と 3 はあの窓にしか置けない。
 * ⚠⚠⚠ **ここを迂回して OBS へ繋ぐ経路を作らないこと。**
 *
 * ## ⚠⚠ 判定の形（§1 の 063c 追補が正）
 *
 * ```
 *   配信イベントを開催中                                  （061l・明示操作＝「開始」）
 * || ( ガチャ演出のトグルが ON かつ ガチャを指す条件が 1 件以上ある )  （063c・明示操作＝トグル）
 * ```
 *
 * - ⚠⚠ **論理和の左右はどちらも「明示操作」に根がある。** 派生値だけで true になる項は 1 つも無い。
 * - ⚠⚠⚠ **右側の連言（AND）を論理和に変えないこと。**
 *   変えると「**ガチャを条件に割り当てただけで OBS へ TCP 接続を張る**」になり、
 *   これは 061i に実在して **064d が hook（`useEffectTemplates`）ごと削除**した形であり、
 *   064c が「画面を開くだけで接続する」として**意図的に却下**した線そのものである。
 * - ⚠ **連言は接続を増やす方向へは決して働かない**（明示操作なしに true にならない）ので、
 *   064d が消した派生値の復活には当たらない。
 *   ⚠ 副次的に「**条件からガチャの割り当てを全部外したら OBS への接続が残り続けない**」も満たす
 *   （064 レビュー S-1 で 1 度踏んだ「旗の取り残し」と同じ壊れ方を、こちら側でも塞ぐ）。
 *   ⚠⚠⚠ **063c 段 1 レビュー S-7（訂正）: 「割り当てを全部消したら」は言い過ぎだった。**
 *   [`referencedGachaIds`] は条件が指す id を数えるだけで、**一覧に実在するかは見ない**
 *   （`saveGachaLibrary` は一覧しか書かないので、**ガチャ本体を消しても条件は残る**）。
 *   ⇒ **参照切れの条件だけが残った状態では、演出が永久に出ないのに接続と表示が維持される。**
 *   ⚠ **§1 違反ではない**（トグルという明示操作は生きている）ので受容する。
 *   ⚠⚠ **再修正トリガー**＝段 2 で「参照切れのときに画面へ理由を出す」を作るとき。
 *   そのとき、ここを一覧の実在と突き合わせる形（＝ガードが**厳しくなる**方向）へ寄せるかを決めること
 *   （⚠ `EffectAssignmentCard` の参照切れ警告と**規則が 2 か所に割れない**ようにすること）。
 *
 * ## ⚠ fail-closed
 *
 * `load*` はいずれも例外時に `false` を返し、[`referencedGachaIds`] は読めなければ空配列を返す
 * （`loadEffectConditions` → `parseConditions` の既定）。
 * ⇒ **読めなければ OBS へ繋がない**側へ倒れる。
 */
export function isStageOverlayRequired(): boolean {
  // ⚠ 061l ぶん（開催中だけ true）。⚠⚠ **この項の書き手 4 か所は 063c では 1 文字も触っていない。**
  if (loadStageOverlayEnabled()) return true;
  // ⚠⚠ 063c ぶん。⚠⚠ **明示トグルを先に見る**（`&&` の短絡＝トグルが OFF なら
  //   localStorage の条件を読みに行かない）。
  // ⚠⚠⚠ **063c 段 1 レビュー Q-2（理由の訂正）: 入れ替えても挙動は同一である**（実測）。
  //   旧コメントは「『条件があるかどうか』だけで判定へ入る形をコードの上でも作らないため」と
  //   書いていたが、それは**読み手への意思表示であって担保ではない**（変異させてもテストは全緑）。
  //   ⚠⚠ **実利はコストのほうにある**——この述語は
  //   `CommentViewerApp`（＝**コメント 1 件ごとに再レンダーする窓**）と `storage` 購読から呼ばれる。
  //   トグルを先に見ることで、**既定 OFF のユーザーでは `loadEffectConditions()` の
  //   JSON.parse ＋ 全件検証を丸ごと回避できる**。⇒ **入れ替えないこと。**
  return loadGachaStageEnabled() && referencedGachaIds().length > 0;
}
