import type { GachaFireDetail } from "./effectFire";

/**
 * ⚠⚠⚠ **063f: ガチャの当選結果を配信のチャットへ書く本文を組み立てる唯一の場所**（純関数）。
 *
 * ## ⚠⚠⚠ §9 の線は「この関数の引数の型」である（⚠ **段 3 で線が動いた**）
 *
 * ⚠⚠ **段 1 まで**: 引数は `prizeLabel` / `rare` の 2 つだけで、
 * **表示名を渡す場所が型として存在しなかった**。根拠は `docs/security.md` §9 の
 * 「追補の追補（063c 段 3）」の**再評価トリガー ③**（表示名が端末外へ出る形は範囲外）である。
 *
 * ⚠⚠⚠ **段 3 から**: 依頼者の判断
 * 「**誰のガチャで何が当たったかがわからないと話にならない**」（2026-08-29）により、
 * **表示名 1 本だけ**を通す側へ移した。⇒ **`docs/security.md` §9 に
 * 「追補の追補（063f・当選者の表示名を配信のチャットへ出す）」を書いた**
 * （⚠ **全文を提示して承認を得てから書き込んだ**）。
 *
 * ⚠⚠⚠ **それでもこの型が関門であることは変わらない。** いま塞いでいるのは
 * **コメント本文・視聴者 id（`provider:userId`）・投げ銭金額・アバター**で、
 * この関数の中でそれらを読もうとすると**コンパイルが落ちる**。
 * ⚠⚠ **`GachaFireDetail` をそのまま受け取る形へ広げないこと**——広げた瞬間、
 * §9 の線を守っているのが「実装者が読まないこと」だけになる（＝守られない）。
 * ⚠ さらに項目を足すときは、**先に §9 へ追補を書き、`security-review` を通すこと。**
 *
 * ## ⚠⚠ 表示名について守ること 3 つ
 *
 * 1. ⚠⚠⚠ **切る規則をここに書かない。** 名前は [`stageViewerName`]（`effectFire.ts`）が
 *    **20 コードポイントで切って `…` を付けた後**の値である。
 *    ⚠ ここで長さをいじると規則が 2 通りになり、片方だけずれる。
 * 2. ⚠⚠ **メンション（`@`）を付けない。** 付けると視聴者に通知が飛び、
 *    **本人が望んでいない呼び出し**になる（§9 追補の明示的な制約）。
 * 3. ⚠⚠ **名前が無いときは代替名を作らない。** `null`（表示名が空）のときは
 *    **景品名だけの文面へ倒す**——「名無しさん」等を発明すると**視聴者に対する嘘**になる。
 *
 * ## ⚠ 検証を新設していない（§8）
 *
 * 本文の検証の持ち主は sidecar の `isAllowedChatMessage` **1 か所だけ**である
 * （型・空・500 文字・**制御文字と改行の拒否**）。⚠ **ここに 2 通り目を書かないこと。**
 *
 * ⚠ **それでも本関数の出力があの検査に落ちない**理由を根拠として残す:
 *   - **制御文字は入らない** … `prizeLabel` は [`gachaPrizeLabel`] の戻り値で、経路 3 つとも
 *     制御文字を通さない（`parseGachaPrize` の `hasControlChar` ／ `isEffectObsSourceName` ／ 定数）。
 *     ⚠ **表示名も同じ**——制御文字の拒否と trim は **Rust 側の取り込みが済ませている**
 *     （`docs/security.md` ⑪。だから `stageViewerName` も検証を持っていない）。
 *   - **500 文字を超えない** … 表示名は最大 20 コードポイント、景品名は最大 24 コードポイント、
 *     OBS のソース名でも最大 200 UTF-16 単位、定型部分は数十文字。合わせても 300 に届かない。
 *   - **空にならない** … `gachaPrizeLabel` は**空文字を返さない**（あちらの注記が正）。
 * ⚠⚠ **再修正トリガー＝本文にユーザーの自由入力を入れる形にするとき**（3 つとも崩れる）。
 *
 * ## ⚠ レアの閾値をここに書かない
 *
 * 「レアか」を決めるのは [`isGachaRarePrize`]（`gachaDraw.ts`）**1 か所**で、
 * ここは `rare: boolean` を受け取るだけである。⚠ **閾値（`GACHA_RARE_MAX_PERCENT`）を
 * 文面側に書き直さないこと**——書くと「抽選が思っているレア度」と
 * 「チャットが主張するレア度」が別実装になる。
 */

/**
 * ⚠⚠⚠ **チャットの本文を組み立てるのに使ってよい値**（[`GachaFireDetail`] の部分集合）。
 *
 * ⚠⚠ **本文・視聴者 id・金額・アバターを含めないことが、この型の存在理由である**（上の JSDoc が正）。
 * ⚠ `GachaFireDetail` から `Pick` しているのは、**あちらのフィールド名が変わったら
 * ここもコンパイルで落ちる**ようにするため（名前を独立に書き写すと静かにずれる）。
 */
export type GachaChatSource = Pick<
  GachaFireDetail,
  "prizeLabel" | "rare" | "viewerName"
>;

/** 063f: レアではない当選の頭。⚠ **視聴者に見えて消せない**ので短く・意味が伝わる形にする。 */
const HIT_PREFIX = "🎉 ";
/** 063f: レア（[`GACHA_RARE_MAX_PERCENT`] 未満）の当選に付ける頭。⚠ 残りは通常と同じにする。 */
const RARE_PREFIX = "✨レア✨ ";

/**
 * 063f: 当選 1 件をチャットへ書く本文にする。
 *
 * ⚠⚠ **引数に載っていない値は書けない**（[`GachaChatSource`] の注記が正・§9）。
 * ⚠ `prizeLabel` は [`gachaPrizeLabel`] が、`viewerName` は [`stageViewerName`] が
 * **決めた後**の値である。**ここで組み立て直さないこと**
 * ——直すと「設定画面の名前」「配信画面の名前」「チャットの名前」が 3 通りになる。
 */
export function buildGachaChatMessage(gacha: GachaChatSource): string {
  const prefix = gacha.rare ? RARE_PREFIX : HIT_PREFIX;
  const prize = `「${gacha.prizeLabel}」`;
  // ⚠⚠ 表示名が無いときは**名前の部分ごと落とす**（代替名を作らない・§9 追補）。
  //   ⚠ `length > 0` も見るのは `parseGachaStageResult` と同じ構え（空文字を `null` と同じに扱う）。
  //   ⚠⚠ `stageViewerName` は空なら `null` を返すので通常ここは通らないが、
  //   **「 さんが」だけが出る**壊れ方を型の外側でも塞いでおく。
  const name = gacha.viewerName;
  if (name === null || name.length === 0) {
    return `${prefix}${prize}が当たりました！`;
  }
  // ⚠⚠⚠ **`@` を付けない**（視聴者に通知を飛ばさない・§9 追補の明示的な制約）。
  return `${prefix}${name} さんが${prize}を当てました！`;
}
