import type { GachaPrize } from "./effectAssignments";

/**
 * 063a: **ガチャの確率表示と抽選**（純関数だけ）。
 *
 * ⚠⚠ **確率の持ち主はこの 1 本だけである。** 表示（[`gachaProbabilityText`]）と
 * 抽選（[`drawGachaPrizeIndex`]）が**同じ重みの合計**を使うことが、
 * 「画面に出ている％と実際の当たり方が一致する」ことの唯一の担保になる。
 * ⚠ **どちらか一方だけを別の場所で計算し直さないこと**（063a 最大の失敗モード）。
 *
 * ⚠ 置き場所が `features/` ではなく `screens/obs-effects/` なのは
 * `effectAssignments.ts` / `effectTrigger.ts` と同じ理由（唯一の消費者がこの画面）。
 *
 * ## ⚠⚠ 穴 D: 丸め規則（⚠⚠⚠ **063a-3 で結論が変わった**）
 *
 * 063a 本文の完了条件は「**確率が自動計算されて常時表示され、合計が常に 100.0% になる**」
 * だったが、**小数第 1 位まで出す限り、丸めた％の和が 100.0 にならない組み合わせが必ず存在する**:
 *
 * | 重み | 各行の表示（相対確率） | 丸めた％の和 |
 * |---|---|---|
 * | 1 / 3 / 6 | 10.0% / 30.0% / 60.0% | 100.0% |
 * | 1 / 3 / 3 | 14.3% / 42.9% / 42.9% | **100.1%** |
 * | 1 / 1 / 1 | 33.3% ×3 | **99.9%** |
 * | 1 ×7 | 14.3% ×7 | **100.1%** |
 *
 * ⚠⚠ **063a-2 はこれを「合計行を固定表記 `"100%"` にする」で回避していた**（規則 (a)）。
 * ⚠⚠⚠ **063a-3 でその前提ごと消えた**——合計は**もう 100% に固定されていない**（各行が独立し、
 * 足りないぶんは「何も出ない」＝はずれになった）ので、**固定表記は嘘になる**。
 * ⇒ **合計行は [`gachaTotalPercentText`] が「重みの合計から 1 回で」出す実際の値である。**
 * ⚠ **丸めた各行の％を足した値は、いまも画面に出さない**（上の表のとおり和が 100.0 にならず、
 * 「設定が間違っている」と誤解させるため）——合計は**必ず重みの合計から直接**求めること。
 *
 * ⚠ **却下した案（063a-2 の時点で却下し、いまも採らない）**:
 *   - **最大剰余法で合計を 100.0% に強制する** … ⚠⚠ **個々の行が真値からずれる**ので、
 *     ユーザーが検算したときに合わない。「1:1:1 なのに 33.4% / 33.3% / 33.3%」は
 *     **説明できない表示**であり、たぬえさ3 の「手計算させる」問題を別の形で持ち込むことになる。
 */

/** 景品が 1 件も無いとき（＝重みの合計が 0）に確率欄へ出す文字。⚠ **0 除算を通らない唯一の経路**。 */
export const GACHA_PROBABILITY_UNAVAILABLE_TEXT = "—";

/**
 * 063a-3: **重み 1 ＝ 0.1%**。⚠⚠ **「合計」ではなく「単位」である。**
 *
 * ⚠⚠⚠ **063a-2 からの方針転換（依頼者の指摘・2026-08-22）。**
 * 063a-2 は「合計を必ず 1000 に保ち、いちばん下の行が残りを吸収する」形だった。
 * ⚠ その結果 **行どうしが連動し、合計 100% を超える入力を「黙って元の値へ戻す」**ことになり、
 * **入力の順番に依存する**（先に下げないと上げられない）＝
 * 依頼者の言葉で「**フォーム側が補正されるからめっちゃ使いにくい**」。
 *
 * ⇒ **合計を保つのをやめた。** いまは **1 行の％はその行だけの値**で、
 *   - 合計が 100% 未満 … **残りは「何も出ない」**（＝はずれ。演出を出したいならはずれの行を足す）
 *   - 合計が 100% 超 … ⚠ **入力は戻さず、画面に赤字で出すだけ**（抽選だけ止める）
 *
 * ⚠⚠⚠ **「％を勝手に直す」処理をこのファイルから 1 つも持たないこと。**
 * 打った数字がそのまま残ることが、この画面の唯一の約束である。
 */
export const GACHA_PERCENT_SCALE = 1000;

/**
 * 重み（0.1% 単位）→ ％の数値。
 *
 * ⚠⚠⚠ **`(weight / 1000) * 100` と書かないこと**（テストが検出した実バグ）。
 * 浮動小数の誤差で **`550` が `55.00000000000001` になり、入力欄にその文字列がそのまま出る**。
 * ⚠ **10 で 1 回割るだけ**なら、0.1% 単位の整数に対して素直な値になる。
 */
export function gachaWeightToPercent(weight: number): number {
  return weight / (GACHA_PERCENT_SCALE / 100);
}

/**
 * ％の数値 → 重み（0.1% 単位の整数）。
 *
 * ⚠ **0.1% 刻みへ四捨五入する**（`10.55` → `106` ＝ 10.6%）。UI は詰めた結果を入力欄へ
 * 書き戻すので**画面から見える**（048 の数値入力と同じ規律）。
 * ⚠ **0.05% 未満だけが 0 になり**、保存層（`parseGachaPrize`）が落とす
 * （`0.05` は四捨五入で `1` ＝ 0.1% になる）。⚠ 実際には UI の [`commitPercent`] が
 * 重み 0 を先に弾くので、ここまで来るのは手で localStorage を編集した場合だけである。
 */
export function gachaPercentToWeight(percent: number): number {
  return Math.round(percent * (GACHA_PERCENT_SCALE / 100));
}

/**
 * 063a-3: **合計が 100% を超えているか**（＝そのままでは抽選できない状態）。
 *
 * ⚠⚠ **これは「エラー」ではなく「まだ直っていない状態」である。**
 * ⚠ **入力を戻したり丸めたりしないこと**——画面に出して、ユーザーに直してもらう。
 */
export function isGachaOverAllocated(prizes: readonly GachaPrize[]): boolean {
  return gachaTotalWeight(prizes) > GACHA_PERCENT_SCALE;
}

/** 重みの合計。⚠ 表示と抽選が**同じ値**を使うために切り出してある。 */
export function gachaTotalWeight(prizes: readonly GachaPrize[]): number {
  let total = 0;
  for (const prize of prizes) total += prize.weight;
  return total;
}

/**
 * 1 行分の**相対**確率表示（重み比を 1 桁で丸める）。
 *
 * ⚠⚠ **`total` が 0 以下なら割らない**——`weight` は 1 以上が保証されている
 * （`parseGachaPrize`）ので通常は到達しないが、**0 除算が起きない理由を型ではなくここで固定する**。
 *
 * ⚠⚠⚠ **063a-3: 表の入力欄はこの関数を使わない。** 入力欄に出すのは
 * [`gachaWeightToPercent`]（＝**ユーザーが打った値そのもの**）である。
 * ⚠ **入力欄に使うと「他の行を足したら自分の％が変わった」が復活する。**
 *
 * ⚠⚠ **レビュー Q-063a-8: いまプロダクションから 1 箇所も呼ばれていない**（消費者は上の
 * 丸め規則テストだけ）。**意図的に残している**——上の穴 D の表（1/3/3 で 100.1%、1/1/1 で 99.9%）は
 * 「**丸めた％の和を画面に出さない**」という現役の決定の根拠そのもので、
 * その検算をコードで表現できる唯一の関数がこれだから。
 * ⚠ **消してよくなる条件＝ 063b が実測の相対確率を出すなら本採用する／
 * 出さないと決まったら、この関数と丸め規則テストを 2 つまとめて消す。**
 */
export function gachaProbabilityText(weight: number, total: number): string {
  if (total <= 0) return GACHA_PROBABILITY_UNAVAILABLE_TEXT;
  return `${((weight / total) * 100).toFixed(1)}%`;
}

/** 063a-3: 合計の表示（⚠ **丸めた％の和ではなく、重みの合計から 1 回で出す**）。 */
export function gachaTotalPercentText(prizes: readonly GachaPrize[]): string {
  return `${gachaWeightToPercent(gachaTotalWeight(prizes)).toFixed(1)}%`;
}

/**
 * 重み付き抽選。**当たった景品の index** を返す（景品が無ければ `-1`）。
 *
 * ⚠⚠ **063a ではテスト抽選ボタンからしか呼ばれない**（配信中の発火は 063b）。
 * 063a 本文は「最小限の抽選関数を本タスクで書いてよい。063b が本実装で置き換える。
 * **どちらにするか実装時に決めてコメントに残す**」としていた
 * ⇒ **書いた。そして 063b はこれを置き換えず、そのまま使うこと。**
 * 理由＝置き換えると「テスト抽選で見た確率」と「本番の確率」が別実装になり、
 * **本タスクの唯一の差別化点（％が信用できること）が壊れる**。
 *
 * ⚠ `random` を引数で受けるのは、**テストで固定するため**である
 * （`Math.random` を直接呼ぶと確率の規則をテストで固定できない）。
 * ⚠ 期待する値域は `[0, 1)`。⚠⚠ **1 以上が来たら「はずれ」（`-1`）になる**
 * （分母が 1000 固定なので `target` が重みの合計を必ず超える）。⚠ 063a-2 の
 * 「最後の景品へ落ちる」という注記は**分母が合計だった頃の記述で、いまは誤り**である。
 */
export function drawGachaPrizeIndex(
  prizes: readonly GachaPrize[],
  random: () => number,
): number {
  if (prizes.length === 0) return -1;
  // ⚠⚠⚠ **063a-3: 分母は合計ではなく 1000 固定である。**
  //   合計で割ると「10% と打ったのに、他の行を足したら 9.7% になった」が起きる
  //   ——それがまさに 063s の痛点（％が信用できない）であり、この画面が消すべきものである。
  //   ⇒ **打った％がそのまま当たる確率になる。**
  const target = random() * GACHA_PERCENT_SCALE;
  let cumulative = 0;
  for (let i = 0; i < prizes.length; i++) {
    cumulative += prizes[i].weight;
    if (target < cumulative) return i;
  }
  // ⚠⚠ **どの景品にも当たらなかった＝「はずれ」**（合計が 100% 未満なら必ずここへ来る）。
  //   ⚠ 最後の景品へ倒さないこと——倒すと「合計 30% なのに必ず何か当たる」になる。
  return -1;
}
