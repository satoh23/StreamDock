/**
 * テーマ CSS の**手前**に置く固定リセット。4 ブロックそれぞれに別の意図がある。
 *
 * ⚠⚠⚠ **4 ブロックすべてが chat 限定**（060f 追修正④・2026-08-08 本人決定）。
 * 課金カードには安定クラスを 1 つも付けなくなった（`CommentList.tsx` の課金分岐参照）ので、
 * `.sd-comment` や `.sd-comment-body` だけで書いても実際には chat にしか当たらない。
 * それでも**当て先を chat 専用クラスで明示している**のは、将来カード側にクラスを戻したときに
 * リセットが黙って課金カードへ漏れるのを防ぐため——**文字列そのものが「chat だけ」を示す**ようにしておく。
 *
 * ### 1. `:where(.sd-comment-chat){position:relative}`（テーマの絶対配置の基準）
 *
 * 060f 追修正③(2026-08-08)。実サンプルの**看板デザイン**は
 * `.yt-live-chat-text-message-renderer::before{position:absolute;left:0;top:20%;height:60%}` ＝
 * **コメント 1 件の枠に対する絶対配置**で縦バーを描く。ところが `.item`（＝ `.sd-comment-chat`）は
 * `position: static` なので、⚠⚠ **基準が窓（プレビューでは `.themePreview` の `contain:paint`）になり
 * バーが左上に飛ぶ**。実テーマで頻出の書き方なので、器の側に基準を与える。
 *
 * ⚠ 追修正④で `.sd-comment` → `.sd-comment-chat` に変えた（当て先は同じ `<li>`）。
 * 追修正③時点は「課金カード側のテーマも同じ罠を踏むから chat 限定にしない」と書いていたが、
 * **課金カードはユーザー CSS の的でなくなった**ので、その理由自体が消えた。
 * ⚠ **既知の限界**: `.item` は `display: grid` なので、テーマが `position:absolute` を**書かずに**
 * `::before` を作ると**グリッド項目になって列を 1 つ占める**（絶対配置なら grid item にならない）。
 *
 * ### 1b. `:where(.sd-comment-chat){padding:0}`（StreamDock 固有の余白を返す）
 *
 * ⚠⚠ 060c 追修正(2026-08-09・実機不具合)。`.item` の `padding: 6px 4px` は **035b で「コメントが詰まって
 * 見える」という本人フィードバックに応えて足した StreamDock 固有の余白**で、純正チャット向けに書かれた
 * テーマはその存在を知らない。テーマが自前で `padding: 22px 24px` を書くと**両方が積み上がって**
 * コメント間が広がりすぎる（実機で確認）。テーマ適用中は既定の装飾を引っ込めるという 3・4 と同じ方針で、
 * ここも返す。
 *
 * ⚠ **3 が `padding` を書かない理由（本文が箱の端に張り付く）はここには当てはまらない。**
 * あちらは `.sd-comment-body` ＝**本文の箱**だが、こちらは `<li>` ＝**コメント 1 件の外枠**で、
 * 本文の内側余白は 3 の対象（`.bubble` の padding）が別に持っている。
 * ⚠ **`.list` の `gap: 6px` と `.item` の `row-gap: 2px` は返さない**——前者は本体コメビュと共有の
 * 宣言（035b の注記どおり触らない）、後者は名前行と吹き出しの間隔でテーマが自分で潰せる。
 * ⚠ **リセットなので `!important` は付けない**（テーマが `.sd-comment-chat{padding:…}` を書けば勝つ）。
 *
 * ### 2. `:where(.sd-comment-chat){--sd-icon-gap:8px}`
 *
 * 既定の 28px は「しっぽの突き出し 20px ＋ 素のすき間 8px」なので、しっぽを描かなくなるぶんを返す。
 * ⚠ **ここだけレイヤー不要**——`.item` が宣言しているのは `--icon-gap` で、`--sd-icon-gap` は
 * **どこも宣言していない読み取り専用の入口**だから競合が無い。
 * ⚠ 逆に `--icon-gap` を直接書くと、同じ要素の `.item` の宣言（より高詳細度）に負けて効かない。
 * ⚠ **しっぽが 8px より長いテーマではアイコンに重なる**。逃げ道は
 * `.sd-comment{--sd-icon-gap:28px}`（`OverlayThemeCard` の注記でユーザーへ案内している）。
 *
 * ### 3. `:where(.sd-comment-body.sd-comment-in-chat){…}`（装飾を落とす）
 *
 * ⚠⚠ **`position` を書いてはいけない。** `.bubble{position:relative}` は**テーマの `::before`
 * （絶対配置のしっぽ）の基準**で、`static` へ戻すとテーマのしっぽが遠い祖先を基準に飛ぶ。
 * ⚠⚠ **`padding` も書かない**（2026-08-08 本人決定）。落とすと、背景しか指定しないテーマで
 * 文字が箱の端に張り付く（純正チャット向けテーマは YouTube 側の余白に依存して書かれている）。
 * ⚠⚠⚠ **`all: unset` にしてはいけない**（下の 4 とは違う）——chat では `.bubble` と `.text` が
 * **同じ 1 枚の `<p>`** なので、`all` を使うと**本文の font-size / color / line-height / margin:0 まで消える**。
 * ここは必ずプロパティを列挙すること。
 * ⚠ **当て先を `.sd-comment-in-chat` に限るのが要点**——`.sd-comment-body` だけにすると
 * 課金カードのボディも平らになり、060f の起票理由①（chat 用テーマが課金カードを壊す）に戻る。
 *
 * ### 4. `:where(.sd-comment-body.sd-comment-in-chat)::before / ::after{all:unset}`（既定のしっぽを白紙に戻す）
 *
 * ⚠⚠ 060f 追修正③(2026-08-08): **`content:none` では不足だった**（実機で「しっぽがズレる」）。
 * `content` だけ止めても、**テーマが `content:""` で疑似要素を復活させた瞬間、テーマが書かなかった
 * 残り全部が `@layer sd-default` の値のまま効く**（`top:12px` / `left:-20px` / `width:0` / `height:0` /
 * `border-style:solid` / `border-color:transparent` / `border-top-width:12px` / `border-bottom-width:12px` /
 * `border-right-width:20px`）。border 三角を全部書くテーマは無事だが、
 * **文字（`content:"◀"`）・回転四角（`transform:rotate(45deg)`）・画像でしっぽを描くテーマは必ず崩れる**。
 * → `all: unset` なら**完全な白紙**から始まる。⚠ `all` は `content` も含む（`content:normal` ＝
 * 疑似要素では `none`）ので、従来の `content:none` の挙動を**包含している**。
 *
 * ⚠⚠ **060f 追修正④(2026-08-08) で `in-chat` を付けた**（追修正③まではあえて外していた）。
 * 当時の理由は「課金カードには既定の疑似要素が無いので無害」だったが、**無害であることと
 * 当て先が chat に閉じていることは別**で、リセットが課金カードにも当たる状態は
 * 「テーマが課金カードを壊す」経路と同じ形をしている。課金カードをユーザー CSS から切り離した以上、
 * リセットも同じ線の内側に揃える。⚠ **当て先クラスを変えるときは 3 と 4 を必ず対で変えること。**
 *
 * ⚠ 末尾の改行は必須——テーマ CSS が `@charset` や `@import` で始まっていても行が混ざらないため。
 */
export const DEFAULT_DECORATION_RESET =
  ":where(.sd-comment-chat){position:relative}\n" +
  ":where(.sd-comment-chat){padding:0}\n" +
  ":where(.sd-comment-chat){--sd-icon-gap:8px}\n" +
  ":where(.sd-comment-body.sd-comment-in-chat){background:none;border:0;border-radius:0;filter:none}\n" +
  ":where(.sd-comment-body.sd-comment-in-chat)::before,\n:where(.sd-comment-body.sd-comment-in-chat)::after{all:unset}\n";

/**
 * テーマ CSS の手前へリセットを連結する。
 *
 * ⚠ **必ずこの関数を通すこと**（呼び出し側で文字列連結を手書きしない）。注入経路は
 * `OverlayApp`（配信窓）と `OverlayThemeCard`（プレビュー）の 2 か所あり、**片方だけ抜けると
 * プレビューと本番で見え方が食い違う**（しかも jsdom はカスケードを解決しないのでテストでは気付けない）。
 * この「2 か所とも通っていること」は静的ガード **(10-m)** が固定している。
 */
export function withDecorationReset(css: string): string {
  return DEFAULT_DECORATION_RESET + css;
}
