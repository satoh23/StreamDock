import { playNotificationSound } from "./audioOutputApi";
import type { NotificationSound } from "./audioOutputApi";
import { NO_AUDIO_OUTPUT_DEVICE } from "./audioOutputPrefs";

/**
 * 059a: 通知音を「鳴らしすぎない」ための層。**音源 ID ごとに独立したクールダウン**を持つ。
 *
 * ⚠ **Web Audio には一切触れない。** 058s の結論（②-軽）で通知音の再生層は Rust（`rodio`）へ移っており、
 * このモジュールがやるのは「`playNotificationSound` を**呼ぶか呼ばないか**を決める」ことだけ。
 * `AudioContext` / `decodeAudioData` / `GainNode` / autoplay の `resume()` はどれも登場しない
 * （059a の当初案にあったこれらの記述は 058a 完了時点で失効している）。
 *
 * ### 責務の線引き
 *
 * | ここでやる | ここでやらない |
 * | --- | --- |
 * | 音源 ID ごとのクールダウン判定 | 出力デバイスの選択・列挙・保存（058a の `audioOutput*.ts`） |
 * | 落としてはいけない音を Rust の同時再生 1 本に譲らせる（059b の `WAITS_FOR_IN_FLIGHT`） | 同時再生の上限そのもの（**Rust の責務・外さない**） |
 * | 未選択なら呼ばない（fail-closed） | 既定デバイスへのフォールバック（**禁止**） |
 * | 失敗を戻り値で伝える | React state の更新・画面表示（`CommentViewerApp` の責務） |
 * | — | 「どのコメントで鳴らすか」の判断（`CommentViewerApp` の責務） |
 * | — | キューイング（溜めて後から連打しない。落とすのが正しい＝親 059 の決定） |
 *
 * ### ⚠ Rust の「同時再生 1 本」との役割の違い（混同しないこと）
 *
 * | | 何のためか | 粒度 | 競合したとき | 触ってよいか |
 * | --- | --- | --- | --- | --- |
 * | Rust の `PLAYING` / `PlaybackGuard`（058a） | **可用性（自己 DoS）対策**。`#[tauri::command(async)]` は tokio の worker を占有するので、積み上がると IPC 全体が詰まる | 音の種類に関係なく**全体で 1 本** | 鳴らさず `Ok(())`（成功で返る） | ⚠ **外さない・緩めない**（docs/security.md のレビュー必須条件） |
 * | このモジュールのクールダウン（059a） | **体験（うるささ）対策**。「どの音を何秒に 1 回まで鳴らすか」 | **音源 ID ごとに独立** | 呼ばずに `"skipped"` | 059 の責務・実機で調整してよい |
 *
 * → ここは Rust の上限に**到達させないための上流の絞り**でもある（上限に当たって音が黙って捨てられる
 * 状態は「クールダウンが効いていないのに音だけ減る」という読み解けない挙動になるため、避ける）。
 * ⚠ 059b で「絞る」だけでは足りないことが分かった——**クールダウンを音ごとに独立させても、
 * コメント音の再生中に来た投げ銭音は Rust に黙って捨てられる**（`"played"` に見える）。
 * そこで `WAITS_FOR_IN_FLIGHT` の音だけ**直前の再生の完了を待ってから invoke する**ようにした。
 * ⚠ **上限そのものは触らない**（docs/security.md のレビュー必須条件が名指し）。あくまで上流で譲るだけ。
 */

/**
 * 059a: 再生要求の結果。
 *
 * ⚠ **例外を投げない**（コメント受信経路を通知音の失敗で巻き添えにしない）が、
 * ⚠⚠ **失敗を握り潰しもしない。** 058a は fail-closed（デバイスが見つからなければ鳴らさない）で、かつ
 * **ホットプラグ監視を持たない**——設定画面を開いた時にしか突き合わせない。ここで失敗を無言で捨てると、
 * **配信中にデバイスを抜いたとき通知音が一切鳴らなくなったことをユーザーが知る手段がゼロ**になる。
 * 「鳴らないほうがマシ」は「鳴らないことに気付けなくてよい」ではない（058a の申し送り）。
 * 呼び出し側は `"failed"` を受けたら**画面に継続表示される indicator を出す**こと。
 */
export type NotificationSoundOutcome = "played" | "skipped" | "failed";

/**
 * 059a: 音源 ID ごとのクールダウン（ミリ秒）。
 *
 * ⚠⚠ **共有カウンタにしない。** 共有すると「コメントが流れている最中に来たスパチャの音が、
 * コメント音のクールダウンで消える」＝**一番気づいてほしい音が鳴らない**という最悪の挙動になる
 * （059b の要求）。
 *
 * ⚠ `Record<NotificationSound, number>` なので、Rust 側で `NotificationSound` に variant を足すと
 * **ここが型エラーになる**（追加漏れを起こせない）。Rust の `ALL_SOUNDS` / `sound_label` と同じ idiom。
 *
 * **`comment` を 600ms にした根拠**:
 * 1. **下限は Rust の占有時間で決まる。** コメント音は 140ms ＋ `PLAYBACK_TAIL`(80ms) ＝ **最低でも約 220ms** の
 *    あいだ Rust の `PLAYING` が立つ。これより短いと「クールダウンは通ったのに Rust に黙って捨てられる」
 *    状態になり、上の表のとおり読み解けない挙動になる。
 *    ⚠ **220ms は下限であって実測値ではない**（レビュー Q-4 で訂正）。`PLAYING` が立つのは
 *    `play_on_device` の**先頭**（`PlaybackGuard::acquire()`）からなので、実際にはさらに
 *    **出力デバイスの再列挙**（`find_output_device`。CoreAudio / WASAPI で数十〜数百 ms かかりうる）と
 *    **ストリームの open**、`wait_until_finished` の**ポーリング粒度 10ms** が乗る。
 *    逆向きに、`Player::empty()` は cpal の 50ms バッファを引き取り終えた時点で true になるので
 *    最大 50ms 早く抜けうる。差し引きで実占有は概ね **150〜350ms**、環境によってはもっと長い。
 *    → ⚠ **実機で値を下げるときも 250ms は下回らないこと。**
 * 2. **上限は体験で決まる。** 600ms なら 1 秒あたり最大 1〜2 回。「コメントが来たと気づく」目的には十分で、
 *    連投時にうるさくない。dev-mock（1800ms 間隔）は素通しなので動作確認では毎回鳴る。
 * 3. 投げ銭音（059b）は独立なので、この 600ms がスパチャの検知を遅らせることはない。
 *
 * **`monetary` を 1500ms にした根拠**（⚠ 059b のタスクファイルは「コメント音より**短くて**よい」と
 * 書いていたが、**実コードに当てると逆になる**ので反転した。理由は 2 と 3）:
 * 1. **下限は同じくRust の占有時間で決まる。** 投げ銭音は 300ms ＋ `PLAYBACK_TAIL`(80ms) に
 *    デバイス再列挙・ストリーム open・ポーリング粒度が乗り、実占有は概ね **400〜550ms**。
 *    1500ms はその約 3 倍で、「クールダウンは通ったのに Rust に黙って捨てられる」帯に入らない。
 *    → ⚠ **実機で下げるときも 600ms は下回らないこと**（コメント音の 250ms より下限が高い＝音が長いため）。
 * 2. **上限は「凌ぐ」対象で決まる。** Twitch のコミュニティギフトは `community_sub_gift(total=N)` と
 *    個別 `sub_gift`×N の**両方**が届き、gift 行が **N+1 個**生成される（043a から残る既存課題。
 *    059b では解消せず**クールダウンで凌ぐ**）。600ms だと到着のばらつきで 2〜3 回鳴ってしまう。
 *    ⚠ **この依存は `CommentViewerApp.notificationSound.test.tsx` が明示的に固定している**
 *    （値を縮めるとレッドになる＝「短くしたら鳴りっぱなしに戻った」を気付ける）。
 * 3. **体験上の上限。** スパチャは連投されにくく、1.5 秒に 1 回鳴れば「見逃さない」目的は満たす。
 *    これ以上伸ばすと「別の視聴者からの 2 件目に気づけない」側が効き始めるのでここで止める。
 * 4. コメント音（600ms）とは**独立**なので、この 1500ms がコメント音を間引くことはない（逆も同様）。
 *
 * ⚠ **実機で調整した最終値と理由をここに残すこと。**
 *
 * `test` が 0 なのは、**テスト再生／試聴はユーザーの明示操作**だから（下記 ⚠ を参照）。
 */
const COOLDOWN_MS: Record<NotificationSound, number> = {
  test: 0,
  comment: 600,
  monetary: 1500,
};

/**
 * 059b: **Rust の「同時再生 1 本」に弾かれてはいけない音**か。
 *
 * ⚠⚠ **クールダウンを独立させただけでは「スパチャは必ず鳴る」は成立しない。** 058a の
 * `PLAYING` / `PlaybackGuard` は音の種類に関係なく**全体で 1 本**で、競合した呼び出しを
 * **鳴らさずに `Ok(())` で返す**——つまりここからは `"played"` に見えて**検出できない**。
 * 実測見積もりで 1 回の占有は 150〜350ms（コメント音）、コメント音が鳴りうる間隔の下限は
 * クールダウンの 600ms なので、**コメントが流れ続けている配信では占有率が 25〜58%**。
 * そこへスパチャが無相関に到着する＝**2〜4 回に 1 回、投げ銭音が黙って捨てられる**計算になる。
 *
 * 対策として、`true` の音だけは**直前に投げた再生の完了を待ってから invoke する**。
 * - ⚠ **固定遅延で投げ直す形にはしない。** 成否が分からないので盲目的な再試行になり
 *   （成功していたら二重に鳴る）、かつ Rust の占有時間を frontend が推測する二重管理になる。
 *   ここで使うのは推測ではなく **Rust が既に返している完了通知**——`play_notification_sound` は
 *   鳴り終わってから resolve し、`PlaybackGuard` は `play_on_device` の末尾で drop されるので
 *   **IPC 応答より先に `PLAYING` が false になる**（`play_on_device` のローカルは宣言の逆順に
 *   drop され、ガードは最初の宣言＝最後に落ちる。Tauri が応答を組むのはその後）。
 *   ⚠ ただし**「待った先で必ずガードを取れる」とまでは言えない**（レビュー S-2 で表現を訂正）。
 *   解決してから再 invoke が Rust へ届くまでの窓に、下記の試聴／テスト再生や同時刻に発射された
 *   コメント音が割り込めば取り損ねる。劣化先は 059a が受容済みの「黙って捨てられる」で、
 *   fail-closed も §9 も壊れないので、確率を大きく下げる対策として受容している。
 * - ⚠ **無限待ちにならない。** 上限は Rust 側（`PLAYBACK_GRACE` 1 秒 ＋ 音の長さ）が持っている。
 * - ⚠ **`comment` は待たせない**（059a の挙動を 1 ビットも変えない）。結果として
 *   「投げ銭音の再生中に来たコメント音は Rust に落とされうる」が、**落ちてよいのはコメント音の側**
 *   なので優先順が正しい向きに出る。
 * - ⚠ **設定画面の試聴／テスト再生はこの関数を通らない**ので追跡対象外。設定を開いている最中に
 *   コメントが届くと従来どおり競合しうるが、配信中の経路ではないので受容する。
 *   ⚠ **その帰結として「コメント音の再生中に試聴を押すと無音になる」ことがある**
 *   （レビュー Q-6）。`SettingsView` が試聴 2 つで `soundPreviewState` を共有しているのは
 *   「押したのに鳴らない」を潰すためだが、**潰せているのは試聴どうしの衝突だけ**で、
 *   コメント受信との衝突は残っている。押し直せば鳴るので受容する。
 *   **再修正トリガー＝設定画面を開いたまま配信する運用が常態になったとき**（そのときは
 *   試聴もこの関数を通す＝ただしクールダウンは通さない、という形になる）。
 *
 * ⚠ **`true` の音は、飛行中の再生が無くても invoke が 1 マイクロタスク遅れる**（解決済みの Promise へ
 * 連結するため）。実挙動としては無害（同じ tick 内）だが、**テストで「呼ばれた」を確かめる前に
 * 1 回 await が要る**ので忘れないこと（`notificationSound.test.ts` に注記あり）。
 *
 * ⚠ `Record<NotificationSound, number>` と同じく、Rust に variant を足すとここが型エラーになる。
 */
const WAITS_FOR_IN_FLIGHT: Record<NotificationSound, boolean> = {
  test: false,
  comment: false,
  monetary: true,
};

/**
 * 音源 ID → 最後に**要求した**時刻（`Date.now()`）。
 *
 * ⚠ **「鳴り終わった時刻」ではなく「invoke を投げた時刻」を記録する。** 理由は 2 つ:
 * - `play_notification_sound` は**鳴り終わってから resolve する**ので、解決を待って記録すると
 *   クールダウンが再生時間ぶん勝手に伸びて意味がぶれる。
 * - **失敗しても記録する**＝デバイスが抜けている間、コメントのたびに invoke を撃ち続けない
 *   （Rust 側は呼ばれるたびに出力デバイスを再列挙するので、無制限の再試行は素直に無駄）。
 *
 * ⚠ **モジュールスコープ＝窓ごとではなくモジュールごとの可変状態**（レビュー指摘・意図どおり）。
 * webview は窓ごとに独立した JS realm なので、実質「窓ごと」になる。かつ通知音を鳴らすのは
 * コメビュ窓（`CommentViewerApp`）だけで、オーバーレイ窓はこのモジュールを import していない。
 * **再修正トリガー＝コメビュ窓以外からも通知音を鳴らすようになったとき**（そのときは窓をまたいだ
 * 抑制が要るかを先に決めること。localStorage 経由の共有は 1 音のために重すぎるので、まず
 * 「鳴らすのは 1 窓だけ」を維持できないかを検討する）。
 */
const lastRequestedAt = new Map<NotificationSound, number>();

/**
 * 059b: **直近に invoke した再生の完了**（`WAITS_FOR_IN_FLIGHT` が true の音が待つ相手）。
 *
 * 成功でも失敗でも「鳴り終わった／もう `PLAYING` は空いている」を意味するので、**必ず解決する形**に
 * 潰しておく（失敗で reject するとチェインが切れて以降の投げ銭音が鳴らなくなる）。
 * 初期値は解決済み＝1 発目は待たずに即 invoke される。
 *
 * ⚠ 溜め込む「キュー」ではない。保持するのは**常に 1 本**（親 059 の「キューイングしない・
 * 落とすのが正しい」は維持している——待つのは `WAITS_FOR_IN_FLIGHT` の音 1 つだけで、
 * 待っている間に来た同じ音はクールダウンが落とす）。
 *
 * ⚠⚠ **代入は「置き換え」ではなく「両方が終わったら」で繋ぐ**（レビュー Q-1 で修正）。
 * 素直に `lastPlayback = started` と置き換えると、これは「最後に**完了する**再生」ではなく
 * 「最後に**invoke した**再生」になり、**より早く終わるものへ巻き戻る**。具体的には:
 *
 * 1. コメント音 C1 を invoke（1 回の占有が 800ms 程度の環境＝`find_output_device` の再列挙が
 *    重い環境では現実的な値。`service.rs` の注記どおり数十〜数百 ms かかりうる）。
 * 2. 直後にスパチャ M1 が来て C1 に連結（C1 の完了後に invoke され、さらに 800ms 鳴る）。
 * 3. C1 のクールダウン明けに来たコメント音 C2 は待たずに invoke され、**Rust に捨てられて
 *    即 `Ok`** ＝ ほぼ即座に解決する。ここで置き換えると `lastPlayback` が M1 の完了を見失う。
 * 4. M1 のクールダウン明けに来たスパチャ M2 が「解決済み」を待って即 invoke ＝
 *    **まだ鳴っている M1 に弾かれて黙って捨てられる**（059b が潰そうとした事象そのもの）。
 *
 * `lastPlayback.then(() => started)` は `started` を**新たに発射しない**（生成済みの Promise を
 * 待つだけ）ので、invoke の回数も順序も変わらない＝キューにはならない。変わるのは
 * 「次の待つ音が何を待つか」だけ。`notificationSound.test.ts` の「飛行中の投げ銭音を、後から
 * 投げたコメント音の完了が追い越さない」が固定している。
 */
let lastPlayback: Promise<void> = Promise.resolve();

/**
 * 059a: 通知音を 1 回鳴らすよう要求する。**鳴り終わるのは待たない**（投げっぱなしでよい）。
 *
 * - `deviceId` が未選択（`""`）なら **invoke しない**＝`"skipped"`。
 *   ⚠⚠ **既定デバイスへ落とさない。** ②-軽の運用では OS 既定＝仮想オーディオデバイス＝**配信に載る側**
 *   なので、落とすと「載せないつもりの通知音が配信に載る」＝この機能の存在理由そのものが壊れる。
 *   鳴らないのは軽微な不便で、載るのは事故（058a の fail-closed をここでも守る）。
 * - 直近 `COOLDOWN_MS[sound]` 以内に同じ音を要求済みなら **invoke しない**＝`"skipped"`。
 *   ⚠ **キューイングしない**（溜めて後から連打しない）。落とすのが正しい。
 * - `WAITS_FOR_IN_FLIGHT[sound]` の音（＝投げ銭音）は、直前の再生が飛行中なら**その完了を待ってから**
 *   invoke する（Rust の同時再生 1 本に弾かれて黙って消えるのを防ぐ。詳細は同定数の注記）。
 *   ⚠ **クールダウンの記録は「待ち始めた時点」で行う**（下記のとおり invoke ではなく要求の時点）。
 *   待ちは最大でも直前の音の残り（数百 ms）なので、クールダウンの意味はぶれない。
 * - それ以外は invoke し、成功で `"played"` / 失敗で `"failed"` に解決する。**reject しない。**
 *   ⚠ **`"played"` は「実際に音が出た」の保証ではない**（レビュー Q-5）。058a の同時再生 1 本の上限に
 *   競合した呼び出しは、Rust が**鳴らさずに `Ok(())` で返す**ため、ここでは `"played"` になる。
 *   ＝試聴／テスト再生とコメント音がぶつかった数 ms の窓では、鳴っていないのに indicator が畳まれうる。
 *   fail-closed は壊れない（既定デバイスへは行かない）ので受容している。
 *   **再修正トリガー＝「鳴ったこと」を UI が強く主張するようになったとき**（例: 再生回数の表示）。
 *   そのときは Rust 側の戻り値を `Ok(bool)` 等に変える必要があり、コマンドの戻り面を変える＝
 *   docs/security.md のレビュー必須条件（音声の再生）に該当する。
 *
 * ⚠ **ユーザーの明示操作（設定画面の試聴・テスト再生）はこの関数を通さないこと。**
 * 押したのに鳴らないのは「壊れている」と見えるので、明示操作にレート制限をかけてはいけない
 * （034c の話者試聴と同じ考え方）。あちらは `audioOutputApi.playNotificationSound` を直接呼び、
 * 連打は「再生中はボタンを disabled」で抑える。
 */
export function requestNotificationSound(
  sound: NotificationSound,
  deviceId: string,
): Promise<NotificationSoundOutcome> {
  if (deviceId === NO_AUDIO_OUTPUT_DEVICE) {
    return Promise.resolve("skipped");
  }

  const now = Date.now();
  const last = lastRequestedAt.get(sound);
  if (last !== undefined && now - last < COOLDOWN_MS[sound]) {
    return Promise.resolve("skipped");
  }
  lastRequestedAt.set(sound, now);

  // 059b: 投げ銭音だけは、直前の再生が終わってから invoke する（Rust の同時再生 1 本に譲る）。
  // ⚠ 連結先が解決した**同じマイクロタスク**で invoke が走るので、その隙間に別のコメント音が
  // 割り込む余地は無い（コメント受信は WS メッセージ＝マクロタスク）。
  // ⚠ 待たない側（`comment` / `test`）は `playNotificationSound` を直に呼ぶので、これが**同期 throw**
  // すると この関数自体が throw する＝「例外を投げない」契約から漏れる（059a 由来・レビュー Q-7）。
  // `invoke` は Promise を返す実装なので同期 throw は現実的に起きず、`Promise.resolve().then(...)` で
  // 包むと待たない音まで 1 マイクロタスク遅れる（StrictMode の冪等化テストが同期前提で書かれている）ため
  // 現状維持とする。**再修正トリガー＝`audioOutputApi` が invoke 以外の同期処理を持つようになったとき。**
  const started = WAITS_FOR_IN_FLIGHT[sound]
    ? lastPlayback.then(() => playNotificationSound(deviceId, sound))
    : playNotificationSound(deviceId, sound);

  // 次の「待つ音」が参照する完了。⚠ **置き換えではなく「両方が終わったら」で繋ぐ**
  //（レビュー Q-1・理由と巻き戻りの筋書きは上記 lastPlayback の JSDoc）。`started` は既に生成済み
  // なので invoke は 1 つも増えない＝キューにはならない。
  // 失敗も「もう鳴っていない」なので解決側へ倒す（reject を伝播させるとチェインが切れる）。
  lastPlayback = lastPlayback
    .then(() => started)
    .then(
      () => undefined,
      () => undefined,
    );

  return started.then(
    () => "played" as const,
    // §9: 例外オブジェクトを覗かない・ログにも出さない（デバイス名／OS のエラー表現を含みうる）。
    // 失敗の種別（AUDIO_DEVICE_UNAVAILABLE / AUDIO_PLAYBACK_FAILED）で分けないのは、
    // ユーザーが取れる行動が同じ（設定でデバイスを選び直す）で、分けても案内が変わらないため。
    () => "failed" as const,
  );
}

/**
 * テスト専用: このモジュールが持つ可変状態（クールダウンの記録と飛行中の再生）を消す。
 *
 * モジュールスコープの `Map` / `Promise` はテスト間で持ち越されるので、これが無いと
 * **テストの実行順で結果が変わる**（とくに未解決の Promise をモックが返したまま次のテストへ
 * 持ち越すと、投げ銭音が永久に待ち続けてタイムアウトする）。本番コードから呼ばないこと。
 *
 * ⚠ 059b で `resetNotificationSoundCooldownForTest` から改名した。消す対象がクールダウンだけでは
 * なくなったのに旧名のままだと、`lastPlayback` を消し忘れる／消していることに気付かない、の
 * どちらかが必ず起きるため。
 *
 * ⚠ **本番モジュールに test-only の口を開ける判断について**（レビュー指摘・意図どおり）。
 * 引数なしで消すだけ＝万一本番から呼ばれても副作用は「次の 1 回が鳴りやすくなる」だけで、
 * fail-closed にも §9 にも影響しない。代替（`Date.now` の依存注入・テストごとの `vi.resetModules()`）は
 * このサイズのモジュールに払うコストとして重く、名前の `ForTest` で意図も表現できている。
 * **再修正トリガー＝この口が「状態を消す」以上のことをしたくなったとき**
 * （状態を注入する・値を書き換える等になったら、素直に依存注入へ作り替えること）。
 */
export function resetNotificationSoundStateForTest(): void {
  lastRequestedAt.clear();
  lastPlayback = Promise.resolve();
}
