/**
 * 061l: **配信イベント**（視聴者参加型の企画）の静的レジストリ。
 *
 * 親設計 061h〜061l（docs/task-board.md「061h〜061l OBSエフェクトの UX 再設計」）の
 * 判断 2・3 に基づき、イベントを**表示専用データ**として定義する。
 * 形は `features/rakuraku/integrationRegistry.ts` をそのまま借りている
 * （一覧カード → 詳細、というまったく同じ導線を作るため。⚠ **あちらは 1 行も変更しない**）。
 *
 * ## ⚠⚠ このファイルの境界
 *
 * - **表示専用データのみ。** 開催の開始/終了は `streamEventRound.ts`、画面は `StreamEventTab.tsx`、
 *   配信画面への描画は `EffectOverlayApp.tsx` が持つ。ここからは何も実行しない。
 * - ⚠⚠ **`id` は「変更しない識別子」**である。localStorage の開催キーに載り、
 *   将来は同梱アセットのファイル名（`/stream-events/<id>.png`）にもなるので、
 *   **一度出したら変えない**（変えると、開催中の保存値が「未知 id」になって
 *   `parseStreamEventRound` に落とされる＝開催が黙って消える）。
 * - ⚠⚠ **外部リソースを読み込まない。** `thumbnail` に入れてよいのは
 *   **同梱物への同一オリジンのパス**（`tauri://localhost` 配下＝`public/`）だけで、
 *   `http(s):` の URL を書かないこと（docs/security.md「外部 script/style/image を読み込まない」）。
 *   ⚠ `src/assets` から `import` もしない——Vite がハッシュ付きのファイル名を吐くので、
 *   **レジストリの値がビルドごとに変わる**（識別子の集合であるべきものが変わってしまう）。
 *
 * ## ⚠⚠ 061l で同梱するのは「コメント数カウンター」1 本だけ（判断 4）
 *
 * 却下したのは 2 つ：**カウントダウンだけ**（コメントを読まない＝「視聴者参加型の器」であることを
 * 1 ミリも実証しない）と、**玉入れの簡易版**（玉の描画・落下・当たり判定が入る＝**次タスクの前借り**）。
 * コメント数カウンターは **玉入れとまったく同じ経路**（コメント受信 → 開催中か判定 → 数を増やす →
 * ステージ窓へ描く）を通りながら、**§9 を 1 バイトも踏まない**（本文も表示名もアバターも金額も持たず、
 * **数だけ**）。⚠ 中身（玉入れ大会）の実装は次タスクで、本タスクが作るのは器だけである。
 */

/** 1 つの配信イベントの定義（表示専用）。 */
export interface StreamEvent {
  /**
   * 内部識別子（例 `"comment-count"`）。⚠⚠ **変更しない**（上のモジュール JSDoc）。
   * ⚠ 開催キーに載る値なので、**第三者データを含めない**（自前の固定文字列だけ）。
   */
  id: string;
  /**
   * 一覧・詳細の左に出すアイコン（絵文字グリフ）。**必須**。
   * ⚠ `thumbnail` を持たないイベントはここへ落ちる（判断 3）。
   */
  icon: string;
  /**
   * 同梱サムネイル画像のパス（任意）。⚠ **`public/` 配下の同一オリジンのパスだけ**
   * （想定は `"/stream-events/<id>.png"`。先例＝`components/Header.tsx` の `<img src="/icon.png">`）。
   *
   * ⚠⚠ **061l では同梱しない**（穴 ε の結論）——見本 1 本は絵文字で足り、
   * 中身の無いプレースホルダ画像を 1 枚増やしても見本の説得力は上がらないため。
   * **分岐（あれば `<img>` / 無ければ絵文字）は実装済みで、テストが両方を固定している。**
   * ⚠ **再修正トリガー＝次タスク（玉入れ大会）で見栄えのするサムネイルを用意するとき。**
   * そのとき `apps/desktop/public/stream-events/<id>.png` を置き、ここに同じパスを書く。
   * ⚠ **`<img onError>` の分岐は作らない**（壊れた画像は取り込みではなく**同梱物**なので、
   * 壊れていれば開発時に気づく＝判断 3）。
   */
  thumbnail?: string;
  /** やりたいこと（一覧カードの見出し・配信画面にもこの文字列を出す）。 */
  title: string;
  /** 何が起きるかの 1 行要約（一覧カードの説明）。 */
  summary: string;
  /** 詳細画面の説明文。 */
  description: string;
  /**
   * 1 回の開催の長さ（ミリ秒）。⚠ **開始時刻に足して `endsAt`（絶対時刻）にする**のがこの値の唯一の用途で、
   * **時間を変える UI は 061l では作らない**（器を通すことが目的なので、選択肢を増やさない）。
   */
  defaultDurationMs: number;
  /** 詳細画面に出す「配信での使い方」の箇条書き。 */
  howTo: readonly string[];
}

/**
 * 同梱イベントの一覧。⚠ **061l は見本 1 本だけ**（判断 4）。
 *
 * ⚠ **import 機能は作らない**（決定事項 4）＝ この配列がイベントの全集合であり、
 * **Rust のファイル操作も新規 IPC も 1 つも増えない**。061c のテンプレート取り込み
 * （`app_data_dir/effects/`）とは完全に別系統で、あちらの判断をやり直す必要は無い。
 */
export const STREAM_EVENT_REGISTRY: readonly StreamEvent[] = [
  {
    id: "comment-count",
    icon: "💬",
    title: "みんなでコメントカウント",
    summary:
      "開催しているあいだに届いたコメントの数を、配信画面に大きく表示します。",
    description:
      "「みんなで 100 コメント！」のように、視聴者と一緒に数を伸ばす企画に使えます。開催を始めると、届いたコメントの数を数えて配信画面に出します。コメントの内容や投稿者の名前は表示しません（数だけを表示します）。",
    // 5 分。⚠ 値の根拠＝「配信の合間に 1 回まわす」長さ。⚠ 変更 UI は作らない（上の JSDoc）。
    defaultDurationMs: 5 * 60_000,
    // ⚠⚠ 教訓 E-2:「ウィンドウ」を**単数で断定しない**（出力窓は用途別に 2 つある）。
    //   ⚠ どのウィンドウに出るかは**表から引ける画面側**（`StreamEventTab`）が名指しする。
    //   ここに「全画面（ステージ）」と直書きすると、呼び方を変えたときにここだけ古くなる
    //   （061k レビュー Q-3 が `EFFECT_OUTPUT_LABEL` へ寄せたのと同じ穴を作らない）。
    howTo: [
      "「適用」を押してから「開始」を押すと、配信画面にイベントが表示されます。",
      "コメントの数は、コメントの取得中だけ増えます（取得はコメントビューアから開始します）。",
      "終了時刻を過ぎると表示は消えますが、表示先のウィンドウは開いたままになります（配信中にウィンドウが消えると、OBS のキャプチャが真っ黒になるため）。",
    ],
  },
];

/**
 * id からイベントを引く。**見つからなければ `null`**（未知 id は「無かったこと」にする）。
 *
 * ⚠ 呼び出し側は必ず `null` を扱うこと——localStorage の保存値は
 * **アプリの更新でレジストリから消えた id** を指しうる（`RakurakuToolsScreen` が
 * 一覧へフォールバックするのと同じ理由）。
 */
export function findStreamEvent(id: string): StreamEvent | null {
  return STREAM_EVENT_REGISTRY.find((e) => e.id === id) ?? null;
}

/**
 * その id が同梱イベントのものか。⚠ **`parseStreamEventRound` の検証に使う**
 * （localStorage は他窓からも書けるので、**使う前に形ではなく「実在するか」で弾く**）。
 */
export function isStreamEventId(id: string): boolean {
  return STREAM_EVENT_REGISTRY.some((e) => e.id === id);
}
